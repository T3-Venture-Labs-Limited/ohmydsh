'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { writeShims, childEnv } = require('../src/shims')

test('writes node/dsh/omd launchers that run Electron as Node (unix and windows forms)', () => {
  const dir = fs.mkdtempSync(path.join(process.env.TMPDIR ?? os.tmpdir(), 'omd-shim-'))
  const files = writeShims({ bin: dir, electron: '/opt/ohmydsh/ohmydsh', dshBin: '/rt/dsh.js', omdBin: '/res/omd.js', platform: 'linux' })
  assert.deepEqual(files.map((f) => path.basename(f)), ['node', 'dsh', 'omd'])
  const dsh = fs.readFileSync(path.join(dir, 'dsh'), 'utf8')
  assert.match(dsh, /ELECTRON_RUN_AS_NODE=1 exec "\/opt\/ohmydsh\/ohmydsh" "\/rt\/dsh\.js" "\$@"/)
  // Windows has no exec bits; the .cmd shims are what run there.
  if (process.platform !== 'win32') assert.equal(fs.statSync(path.join(dir, 'dsh')).mode & 0o111, 0o111)
  const win = writeShims({ bin: dir, electron: 'C:\\ohmydsh.exe', dshBin: 'C:\\dsh.js', omdBin: 'C:\\omd.js', platform: 'win32' })
  assert.match(fs.readFileSync(win[1], 'utf8'), /set ELECTRON_RUN_AS_NODE=1\r\n"C:\\ohmydsh\.exe" "C:\\dsh\.js" %\*/)
  fs.rmSync(dir, { recursive: true })
})
test('child environment: shims first on PATH, DSH_HOME set, Electron acts as Node', () => {
  const env = childEnv({ base: { PATH: '/usr/bin', HOME: '/h' }, bin: '/rt/bin', pnpmDir: '/rt/pnpm', dshHome: '/dsh', platform: 'linux' })
  assert.equal(env.PATH, '/rt/bin:/rt/pnpm:/usr/bin'); assert.equal(env.DSH_HOME, '/dsh'); assert.equal(env.ELECTRON_RUN_AS_NODE, '1'); assert.equal(env.HOME, '/h')
  assert.equal(childEnv({ base: { Path: 'C:\\x' }, bin: 'b', pnpmDir: 'p', dshHome: 'd', platform: 'win32' }).PATH, 'b;p;C:\\x')
})
test('a real Node as the runtime: launchers do NOT set ELECTRON_RUN_AS_NODE, and the child env drops it (bundled Node on Linux)', () => {
  const dir = fs.mkdtempSync(path.join(process.env.TMPDIR ?? os.tmpdir(), 'omd-shim-'))
  const files = writeShims({ bin: dir, electron: '/res/node/bin/node', dshBin: '/rt/dsh.js', omdBin: '/res/omd.js', platform: 'linux', electronAsNode: false })
  assert.equal(fs.readFileSync(files[1], 'utf8'), '#!/bin/sh\nexec "/res/node/bin/node" "/rt/dsh.js" "$@"\n')
  assert.equal(fs.readFileSync(files[0], 'utf8'), '#!/bin/sh\nexec "/res/node/bin/node"  "$@"\n')
  const win = writeShims({ bin: dir, electron: 'C:\\n\\node.exe', dshBin: 'C:\\dsh.js', omdBin: 'C:\\omd.js', platform: 'win32', electronAsNode: false })
  assert.doesNotMatch(fs.readFileSync(win[1], 'utf8'), /ELECTRON_RUN_AS_NODE/)
  const env = childEnv({ base: { PATH: '/usr/bin', ELECTRON_RUN_AS_NODE: '1' }, bin: '/rt/bin', pnpmDir: '/rt/pnpm', dshHome: '/dsh', platform: 'linux', electronAsNode: false })
  assert.equal(env.ELECTRON_RUN_AS_NODE, undefined)
  fs.rmSync(dir, { recursive: true })
})
test('paths with spaces and special characters stay one argument (sh and cmd)', () => {
  const dir = fs.mkdtempSync(path.join(process.env.TMPDIR ?? os.tmpdir(), 'omd-shim-'))
  const sh = writeShims({ bin: dir, electron: '/Applications/My Apps/ohmydsh.app/Contents/Resources/node/bin/node', dshBin: '/Users/a b/$HOME/dsh.js', omdBin: '/o.js', platform: 'darwin', electronAsNode: false })
  assert.equal(fs.readFileSync(sh[1], 'utf8'), '#!/bin/sh\nexec "/Applications/My Apps/ohmydsh.app/Contents/Resources/node/bin/node" "/Users/a b/\\$HOME/dsh.js" "$@"\n')
  const win = writeShims({ bin: dir, electron: 'C:\\Users\\First Last\\AppData\\Local\\Programs\\ohmydsh\\resources\\node\\node.exe', dshBin: 'C:\\Users\\First Last\\AppData\\Roaming\\ohmydsh\\runtime\\dsh.js', omdBin: 'C:\\o 100%.js', platform: 'win32', electronAsNode: false })
  assert.equal(fs.readFileSync(win[1], 'utf8'), '@echo off\r\n"C:\\Users\\First Last\\AppData\\Local\\Programs\\ohmydsh\\resources\\node\\node.exe" "C:\\Users\\First Last\\AppData\\Roaming\\ohmydsh\\runtime\\dsh.js" %*\r\n')
  assert.match(fs.readFileSync(win[2], 'utf8'), /"C:\\o 100%%\.js" %\*/)
  fs.rmSync(dir, { recursive: true })
})
