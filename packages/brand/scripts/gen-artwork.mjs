// Regenerates src/artwork/paths.ts from assets/mark.svg and assets/wordmark.svg (the repository's brand sources).
// Run: node scripts/gen-artwork.mjs   (check mode: node scripts/gen-artwork.mjs --check, used by `pnpm run check`)
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = (f) => readFileSync(resolve(root, 'assets', f), 'utf8')
const attr = (svg, name) => {
  const m = svg.match(new RegExp(`\\s${name}="([^"]+)"`))
  if (m === null) throw new Error(`gen-artwork: ${name} not found`)
  return m[1]
}
const mark = read('mark.svg')
const word = read('wordmark.svg')
const out = `// artwork: generated by scripts/gen-artwork.mjs from assets/mark.svg and assets/wordmark.svg. Do not edit by hand.
export const MARK_VIEWBOX = ${JSON.stringify(attr(mark, 'viewBox'))}
export const MARK_TRANSFORM = ${JSON.stringify(attr(mark, 'transform'))}
export const MARK_PATH = ${JSON.stringify(attr(mark, 'd'))}
export const WORDMARK_VIEWBOX = ${JSON.stringify(attr(word, 'viewBox'))}
export const WORDMARK_PATH = ${JSON.stringify(attr(word, 'd'))}
`
const file = resolve(root, 'src/artwork/paths.ts')
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== out) { console.error('gen-artwork: src/artwork/paths.ts is stale; run node scripts/gen-artwork.mjs'); process.exit(1) }
  console.log('gen-artwork: ok')
} else { writeFileSync(file, out); console.log('gen-artwork: wrote src/artwork/paths.ts') }
