// @vitest-environment node
// /m shows only what the full UI shows as chat rows: the person's own messages (source.kind === "user"), assistant text,
// and tool calls collapsed to "Used <tool>". Host-injected context (runtime-context, skill-catalog, time-context,
// model-selection, composio, ...) must never become a bubble. The fixture is recorded from the dev host's real
// session/events output (texts truncated; structure and source kinds untouched).
import { readFileSync } from 'node:fs'
import { runInNewContext } from 'node:vm'
import { describe, expect, it } from 'vitest'

// Load the page script exactly as the browser does (a classic script that publishes window.PwaEvents).
const sandbox: { window: Record<string, unknown> } = { window: {} }
runInNewContext(readFileSync(new URL('../public/m/events.js', import.meta.url), 'utf8'), sandbox)
const { parseEvents, isHumanUserMessage, textOf } = sandbox.window['PwaEvents'] as {
  parseEvents(records: unknown[]): { seq: number; role: string; text: string }[]
  isHumanUserMessage(event: unknown): boolean
  textOf(content: unknown): string
}
const recorded = JSON.parse(readFileSync(new URL('./fixtures/recorded-session-events.json', import.meta.url), 'utf8')) as { event: { seq: number; type: string; data: { source?: { kind: string } } } }[]

const user = (seq: number, source: unknown, text: string) => ({ event: { seq, type: 'user/message', data: { content: [{ type: 'text', text }], source } } })

describe('recorded events', () => {
  const rows = parseEvents(recorded)
  it('the fixture really contains every injected source kind the host produces', () => {
    const kinds = new Set(recorded.filter((r) => r.event.type === 'user/message').map((r) => r.event.data.source?.kind))
    for (const k of ['user', 'runtime-context', 'skill-catalog', 'time-context', 'composio']) expect(kinds.has(k), k).toBe(true)
  })
  it('keeps exactly one user row (the human one) and drops all injected context', () => {
    const users = rows.filter((r) => r.role === 'user')
    expect(users).toHaveLength(1)
    expect(users[0]!.seq).toBe(10)
    for (const r of rows) {
      expect(r.text).not.toMatch(/<system-reminder>/)
      expect(r.text).not.toMatch(/^Time sampled while preparing/)
      expect(r.text).not.toMatch(/COMPOSIO TRIGGER/)
    }
  })
  it('shows assistant text and a collapsed "Used <tool>" for tool calls; tool results and turn markers are hidden', () => {
    expect(rows.some((r) => r.role === 'assistant' && r.text.length > 0)).toBe(true)
    const tools = rows.filter((r) => r.role === 'tool')
    expect(tools.length).toBeGreaterThan(0)
    for (const t of tools) expect(t.text).toMatch(/^Used [\w.-]+$/)
    expect(rows.every((r) => ['user', 'assistant', 'tool'].includes(r.role))).toBe(true)
  })
})

describe('source rule', () => {
  it('only source.kind "user" is human', () => {
    expect(isHumanUserMessage(user(1, { kind: 'user', rpcId: 'x' }, 'hi').event)).toBe(true)
    for (const kind of ['runtime-context', 'skill-catalog', 'time-context', 'model-selection', 'retry', 'composio', 'schedule', 'compact-checkpoint', 'system']) {
      expect(isHumanUserMessage(user(1, { kind }, 'x').event), kind).toBe(false)
    }
  })
  it('treats a missing or malformed source as injected (fail closed), and hides a model-selection notice', () => {
    expect(isHumanUserMessage(user(1, undefined, 'x').event)).toBe(false)
    expect(isHumanUserMessage({ type: 'user/message' })).toBe(false)
    const notice = user(2, { kind: 'model-selection', form: 'notice' }, '[model changed: assistant turns above this point were generated by claude-haiku-5-5]')
    expect(parseEvents([notice])).toEqual([])
  })
  it('hides a human-kind message that has no text (image-only or empty continuation)', () => {
    expect(parseEvents([{ event: { seq: 1, type: 'user/message', data: { content: [{ type: 'image' }], source: { kind: 'user' } } } }])).toEqual([])
  })
  it('does not show reasoning, only text parts, and numbers tool rows after their message', () => {
    const msg = { event: { seq: 10, type: 'assistant/message', data: { message: { content: [
      { type: 'reasoning', text: 'secret thoughts' }, { type: 'text', text: 'Hello' }, { type: 'tool-call', id: 'a', name: 'bash', arguments: '{}' }, { type: 'tool-call', id: 'b', name: 'schedule_create', arguments: '{}' },
    ] } } } }
    const rows = parseEvents([msg])
    expect(rows.map((r) => `${r.role}:${r.text}`)).toEqual(['assistant:Hello', 'tool:Used bash', 'tool:Used schedule_create'])
    expect(rows.map((r) => r.seq)).toEqual([10, 10.03, 10.04]) // after the message, in call order (offset = part index)
    expect(JSON.stringify(rows)).not.toContain('secret')
  })
  it('textOf joins text parts only', () => {
    expect(textOf([{ type: 'text', text: 'a' }, { type: 'image' }, { type: 'text', text: 'b' }])).toBe('a\nb')
  })
})
